def seed(db: Session):
    existing_count = db.query(Candidate).count()
    if existing_count >= len(CANDIDATES):
        logger.info(f"Database already has {existing_count} candidates. Skipping seed.")
        return []

    created = []
    for data in CANDIDATES:
        c = Candidate(**data)
        db.add(c)
        db.flush()
        created.append(c)
    db.commit()
    logger.info(f"Seeded {len(created)} candidates.")
    return created


def score_all(db: Session, candidates):
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        logger.warning("ANTHROPIC_API_KEY not set — skipping AI scoring.")
        return

    try:
        service = ScoringService()
    except ValueError as e:
        logger.error(f"Cannot initialize scoring service: {e}")
        return

    for candidate in candidates:
        logger.info(f"Scoring candidate: {candidate.full_name} ...")
        try:
            candidate_data = {
                "full_name": candidate.full_name,
                "age": candidate.age,
                "school_type": candidate.school_type.value,
                "city": candidate.city,
                "achievements_text": candidate.achievements_text,
                "essay_text": candidate.essay_text,
            }
            score_data = service.score_candidate(candidate_data)
            score = Score(candidate_id=candidate.id, **score_data)
            db.add(score)
            db.commit()
            logger.info(
                f"  -> overall_score={score.overall_score}, "
                f"ai_probability={score.ai_probability}"
            )
        except Exception as e:
            logger.error(f"  -> Failed to score {candidate.full_name}: {e}")
            db.rollback()


if __name__ == "__main__":
    create_tables()
    with SessionLocal() as db:
        candidates = seed(db)
        if candidates:
            score_all(db, candidates)
    logger.info("Done.")
