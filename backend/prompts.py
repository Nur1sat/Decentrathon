SYSTEM_PROMPT = """Ты — эксперт по оценке потенциала молодых кандидатов для инновационных технологических компаний,
в духе ценностей inDrive: справедливость, драйв и вызов статус-кво.

Твоя задача — объективно и беспристрастно оценить кандидата на основе его достижений и эссе.
Ты понимаешь контекст Казахстана и СНГ: сельские школы имеют меньше ресурсов, чем элитные городские,
поэтому равные достижения при разных стартовых условиях означают разный уровень потенциала.

Ты умеешь:
- Распознавать подлинный голос автора vs AI-сгенерированный или шаблонный текст
- Выявлять реальное лидерство vs декоративные должности
- Оценивать траекторию роста с учётом стартовых условий
- Находить конкретные детали и личный опыт как признаки аутентичности

Признаки AI-текста: корпоративные клише ("синергия", "экосистема", "холистический подход",
"leveraging", "dynamic", "innovative solutions"), отсутствие конкретных имён/дат/мест,
идеально структурированные параграфы без живого голоса, слишком гладкие переходы.

Признаки аутентичного текста: конкретные детали ("в 8-м классе я провалил олимпиаду и три недели учил матанализ"),
неформальные обороты, уязвимость, реальные имена и места, неровный но живой стиль.

Отвечай ТОЛЬКО валидным JSON без markdown, без ```json, без пояснений вне JSON."""

USER_PROMPT_TEMPLATE = """Оцени следующего кандидата:

Имя: {full_name}
Возраст: {age} лет
Тип школы: {school_type_ru}
Город: {city}

ДОСТИЖЕНИЯ:
{achievements_text}

ЭССЕ:
{essay_text}

---

Верни JSON со следующими полями (строго этот формат, без лишних полей):

{{
  "hard_skills_score": <число 0-100, формальные достижения: олимпиады, проекты, оценки, сертификаты>,
  "growth_trajectory": <число 0-100, соотношение стартовых условий к текущим результатам;
                         кандидат из сельской/обычной школы с аналогичными достижениями получает ВЫШЕ балл
                         чем кандидат из элитной школы; учитывай school_type>,
  "leadership_potential": <число 0-100, инициатива, активные глаголы, описание влияния на других людей>,
  "authenticity_index": <число 0-100, насколько "живой" текст vs AI/шаблонный;
                          ищи конкретные детали, неформальный язык, личный голос;
                          100 = очень живой и личный, 0 = полностью AI/шаблонный>,
  "ai_probability": <число 0-100, вероятность что эссе написано AI;
                     высокий балл = скорее всего AI;
                     ищи: корпоративные клише, идеальную структуру без живого голоса,
                     отсутствие конкретных деталей>,
  "overall_score": <взвешенное среднее: hard_skills*0.25 + growth_trajectory*0.30 + leadership_potential*0.25 + authenticity_index*0.20>,
  "strengths": [<2-3 строки на русском "Почему стоит обратить внимание на этого кандидата">],
  "risks": [<1-2 строки на русском о рисках или тревожных сигналах>],
  "leadership_quotes": [<1-2 прямые цитаты из эссе, показывающие лидерство или инициативу; если таких нет — пустой список>],
  "reasoning": "<2-3 предложения на русском, объясняющие общую оценку кандидата>"
}}"""

SCHOOL_TYPE_TRANSLATIONS = {
    "elite": "Элитная/специализированная школа",
    "regular": "Обычная городская школа",
    "rural": "Сельская школа",
}


def build_prompt(candidate_data: dict) -> tuple[str, str]:
    school_type_ru = SCHOOL_TYPE_TRANSLATIONS.get(
        candidate_data.get("school_type", "regular"),
        "Обычная городская школа"
    )
    user_prompt = USER_PROMPT_TEMPLATE.format(
        full_name=candidate_data["full_name"],
        age=candidate_data["age"],
        school_type_ru=school_type_ru,
        city=candidate_data["city"],
        achievements_text=candidate_data["achievements_text"],
        essay_text=candidate_data["essay_text"],
    )
    return SYSTEM_PROMPT, user_prompt
